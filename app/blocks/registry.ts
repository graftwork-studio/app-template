import type { InventoryCategory } from "./inventory";

/**
 * Every block in the template: the single source of truth for the gallery at
 * /blocks and for the tests. Each built block's source is in app/blocks/<id>/.
 * See BLOCKS.md for how to add one.
 *
 * This file holds data only, so tests can import it without React.
 */

export type BlockCategory = InventoryCategory;

type BlockBase = {
  /** Kebab-case, the same as the upstream id, the folder name and the Figma component name. */
  id: string;
  title: string;
  category: BlockCategory;
  description: string;
  /** The upstream block it was based on. Upstream doesn't version blocks, so this is the shadcn CLI version current when it was fetched. */
  upstream: { id: string; style: "aria-nova" | "new-york-v4"; version: string };
  /** The URL of its component set in the Graftwork Blocks Figma file, or null until it exists. */
  figma: string | null;
};

export type BuiltBlock = BlockBase & { status: "built" };
export type ParkedBlock = BlockBase & { status: "parked"; /** Why it can't be built from @graftwork/ui yet. */ reason: string };
export type Block = BuiltBlock | ParkedBlock;

